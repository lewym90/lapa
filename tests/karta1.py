# 1.17: karta psa w 5 krokach (przyjęcie nowego psa i edycja), automatyczny zapis, „Uzupełnij n/5”, szkic opisu, telefon i komputer.
from playwright.sync_api import sync_playwright
from wspolne import *


def dog(P, imie):
    return P.evaluate("async(n)=>(await (await import('/js/store.js')).list('psy')).find(x=>x.imie===n)", imie)


with sync_playwright() as p:
    b = p.chromium.launch()
    ca, pg = newpage(b); errs = []; pg.on('pageerror', lambda e: errs.append(str(e)))
    login(pg, 'Ania')
    # wejścia
    go(pg, '#/start', 800)
    check('Start: przycisk „Przyjmij nowego psa”', pg.locator('a.przyjmij[href="#/karta/nowy"]').count() == 1)
    go(pg, '#/psy', 800)
    check('Psy: przycisk „Przyjmij nowego psa”', pg.locator('.fab[data-act=a-newdog]').count() == 1)
    pg.click('.fab[data-act=a-newdog]'); pg.wait_for_timeout(800)
    check('przycisk otwiera kartę', pg.evaluate('location.hash') == '#/karta/nowy' and 'Podstawy' in pg.inner_text('.khead'))
    check('bez imienia kroki 2–5 zablokowane', pg.locator('.kst[disabled]').count() == 4)
    pg.click('[data-k=next]'); pg.wait_for_timeout(300)
    check('bez imienia nie przejdzie dalej', 'Wpisz imię' in pg.inner_text('#kerr') and pg.evaluate('location.hash') == '#/karta/nowy')
    pg.click('[data-seg=plec][data-v=samiec]')  # przed imieniem: czeka i zapisze się razem z imieniem
    pg.fill('#k_imie', 'Burek'); pg.wait_for_timeout(1300)
    d = dog(pg, 'Burek')
    check('po wpisaniu imienia pies jest zapisany', d and d['nowy'] and d['plec'] == 'samiec' and d['status'] == 'schronisko', d)
    check('adres zmienia się na kartę psa', pg.evaluate('location.hash') == f"#/karta/{d['id']}/1")
    check('napis „Zapisano”', 'Zapisano' in pg.inner_text('#kzap'))
    pg.fill('#k_waga', '25 kg'); pg.wait_for_timeout(1200)
    check('pole zapisuje się samo', dog(pg, 'Burek')['waga'] == '25 kg')
    pg.fill('#k_boks', ' 12b! '); pg.locator('#k_boks').blur(); pg.wait_for_timeout(800)
    check('boks oczyszczony', dog(pg, 'Burek')['boks'] == '12b')
    # wyjście w środku i powrót: wszystko jest
    pg.click('[data-k=wyjdz]'); pg.wait_for_timeout(800)
    check('wyjście → karta psa', pg.evaluate('location.hash') == f"#/psy/{d['id']}")
    go(pg, '#/psy', 800); k = pg.locator('.dcard', has_text='Burek')
    check('lista: znaczek „Uzupełnij 0/5”', 'Uzupełnij 0/5' in k.inner_text(), k.inner_text())
    check('lista: kafelek prowadzi do pierwszego brakującego kroku', k.get_attribute('href') == f"#/karta/{d['id']}/1")
    k.click(); pg.wait_for_timeout(900)
    check('po powrocie pola są wypełnione', pg.input_value('#k_imie') == 'Burek' and pg.input_value('#k_waga') == '25 kg' and pg.locator('[data-seg=plec][data-v=samiec].on').count() == 1)
    pg.click('[data-seg=wiek_kat][data-v=mlody]'); pg.click('[data-seg=wielkosc][data-v="duży"]'); pg.wait_for_timeout(600)
    pg.click('[data-seg=wiek_kat][data-v=mlody]'); pg.wait_for_timeout(600)
    check('ponowne dotknięcie odznacza', 'wiek_kat' not in dog(pg, 'Burek'))
    pg.click('[data-seg=wiek_kat][data-v=senior]'); pg.wait_for_timeout(600)
    check('krok 1 uzupełniony', pg.locator('.kst').nth(0).get_attribute('class').find('ok') >= 0)
    # Enter przechodzi do następnego pola
    pg.focus('#k_wiek'); pg.keyboard.press('Enter'); check('Enter → następne pole', pg.evaluate('document.activeElement.id') == 'k_waga')
    # krok 2
    pg.click('[data-k=next]'); pg.wait_for_timeout(900)
    check('Dalej → krok 2', pg.evaluate('location.hash').endswith('/2') and 'Zdrowie' in pg.inner_text('.khead'))
    check('numer czipa ukryty, dopóki czip ≠ tak', pg.locator('#kchip').is_hidden())
    pg.click('[data-seg="zdr.czip"][data-v=tak]'); check('czip tak → pole numeru', pg.locator('#kchip').is_visible())
    for k2 in ['szczep', 'odrob', 'kastr']: pg.click(f'[data-seg="zdr.{k2}"][data-v="?"]')
    pg.wait_for_timeout(800)
    check('zdrowie zapisane', dog(pg, 'Burek')['zdr'] == {'czip': 'tak', 'szczep': '?', 'odrob': '?', 'kastr': '?'})
    pg.click('[data-k=prev]'); pg.wait_for_timeout(800); check('Wstecz → krok 1', pg.evaluate('location.hash').endswith('/1'))
    pg.click('.kst[data-go="3"]'); pg.wait_for_timeout(800); check('dotknięcie kroku → krok 3', 'Charakter' in pg.inner_text('.khead'))
    pg.click('[data-seg="ocena.psy"][data-v=ok]'); pg.click('[data-tag="energiczny"]'); pg.wait_for_timeout(800)
    d = dog(pg, 'Burek'); check('charakter i cechy (forma męska)', d['ocena'] == {'psy': 'ok'} and d['tagi'] == ['energiczny'], d)
    pg.click('.kst[data-go="5"]'); pg.wait_for_timeout(800)
    pg.click('[data-k=szkic]'); pg.wait_for_timeout(1200)
    d = dog(pg, 'Burek')
    check('szkic: hasło i opis w formie męskiej', d['haslo'].startswith('BUREK – ') and 'Burek to duży senior' in d['opis'] and 'zaczipowany' in d['opis'], d.get('opis'))
    pg.click('[data-k=szkic]'); pg.wait_for_selector('[data-yes]')
    check('drugi szkic pyta o zastąpienie', 'Zastąpić' in pg.inner_text('#sheet-root')); pg.click('[data-no]'); pg.wait_for_timeout(300)
    pg.fill('#k_opis', 'Mój własny opis.'); pg.wait_for_timeout(1200)
    check('własny opis zapisany', dog(pg, 'Burek')['opis'] == 'Mój własny opis.')
    pg.click('[data-kanal=fb]'); pg.click('[data-seg=status][data-v=do_adopcji]'); pg.wait_for_timeout(800)
    d = dog(pg, 'Burek'); check('kanał i status', d['kanaly'].get('fb') and d['status'] == 'do_adopcji', d)
    check('podgląd ogłoszenia', 'Mój własny opis.' in pg.inner_text('.kpodglad-in'))
    go(pg, '#/psy', 800); k = pg.locator('.dcard', has_text='Burek')
    check('lista: „Uzupełnij 4/5”, prowadzi do zdjęć', 'Uzupełnij 4/5' in k.inner_text() and k.get_attribute('href').endswith('/4'), k.inner_text())
    go(pg, f"#/psy/{d['id']}", 900)
    check('karta psa: wiersz „Karta psa: 4 z 5”', 'Karta psa: 4 z 5' in text(pg))
    pg.click('[data-act=dog-edit]'); pg.wait_for_timeout(800)
    check('„Edytuj” otwiera kartę na kroku 1', pg.evaluate('location.hash') == f"#/karta/{d['id']}/1")
    go(pg, '#/nowe', 900)
    check('#/nowe → lista „Do uzupełnienia”', pg.locator('[data-act=dog-filter][data-k=nowe].on').count() == 1 and 'Burek' in text(pg))
    # zdjęcia (krok 4) → komplet
    go(pg, f"#/karta/{d['id']}/4", 900)
    pg.set_input_files('#kpf', ['/home/claude/proto2/tmpimg/p0.jpg', '/home/claude/proto2/tmpimg/p1.jpg']); pg.wait_for_timeout(2500)
    d = dog(pg, 'Burek'); check('zdjęcia: 2, pierwsze główne', len(d['moje_zdjecia']) == 2 and d['glowne'] == d['moje_zdjecia'][0], d.get('moje_zdjecia'))
    pg.locator('[data-ph=main]').nth(1).click(); pg.wait_for_timeout(600)
    d = dog(pg, 'Burek'); check('zmiana zdjęcia głównego', d['glowne'] == d['moje_zdjecia'][1])
    pg.locator('[data-ph=del]').nth(0).click(); pg.locator('[data-ph=del]').nth(0).click(); pg.wait_for_timeout(700)
    d = dog(pg, 'Burek'); check('usunięcie zdjęcia (z potwierdzeniem)', len(d['moje_zdjecia']) == 1, d.get('moje_zdjecia'))
    pg.wait_for_timeout(1500)
    check('komplet: karta oznaczona jako gotowa', bool(dog(pg, 'Burek').get('karta_gotowa')))
    go(pg, '#/psy', 800); pg.click('[data-act=dog-filter][data-k=aktywne]'); pg.wait_for_timeout(500); check('komplet: bez znaczka', 'Uzupełnij' not in pg.locator('.dcard', has_text='Burek').inner_text())
    # imienia nie da się wyczyścić
    go(pg, f"#/karta/{d['id']}/1", 800); pg.fill('#k_imie', ''); pg.wait_for_timeout(1200)
    check('puste imię nie kasuje imienia', dog(pg, 'Burek') is not None)
    # wolontariusz: karta niedostępna, widzi psa i zdrowie
    sync(pg, 1500)
    cv, pv = newpage(b); login(pv, 'Wola', WOL); sync(pv, 1500)
    go(pv, f"#/karta/{d['id']}/1", 800); check('wolontariusz: karta tylko dla administratora', pv.evaluate('location.hash') == '#/start')
    w = pv.evaluate("async(i)=>(await (await import('/js/store.js')).get('psy',i))", d['id'])
    check('wolontariusz: dane psa bez czipa i pochodzenia', w and 'chip' not in w and 'pochodzenie' not in w and w.get('zdr', {}).get('czip') == 'tak', w)
    # komputer: kroki z boku, dwie kolumny, podgląd
    cd, pd = newpage(b, {'width': 1440, 'height': 900}); login(pd, 'Ania'); sync(pd, 1500)
    go(pd, f"#/karta/{d['id']}/1", 900)
    check('komputer: kroki w kolumnie z lewej', pd.evaluate("getComputedStyle(document.querySelector('.kkroki')).flexDirection") == 'column')
    check('komputer: pola w dwóch kolumnach', pd.evaluate("getComputedStyle(document.querySelector('.kpola')).gridTemplateColumns.split(' ').length") == 2)
    check('komputer: podgląd z prawej', pd.locator('.kpodglad').is_visible() and 'Burek' in pd.inner_text('.kpodglad'))
    check('komputer: przyciski w formularzu (nie przyklejone)', pd.evaluate("getComputedStyle(document.querySelector('.knav')).position") == 'static')
    pd.focus('#k_waga'); pd.keyboard.press('Control+Enter'); pd.wait_for_timeout(900)
    check('komputer: Ctrl+Enter = Dalej', pd.evaluate('location.hash').endswith('/2'))
    check('bez błędów strony', not errs, errs)
    koniec('karta1')
